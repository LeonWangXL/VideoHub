def child_env() -> dict:
    env = os.environ.copy()

    # The helper launches `python -m yt_dlp`; force UTF-8 so Windows console
    # encoding does not corrupt Unicode titles in captured output.
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"

    return env


def parse_progress(line: str) -> dict | None:
    marker = "VH_PROGRESS:"

    if marker not in line:
        return None

    parts = (
        line
        .split(marker, 1)[1]
        .strip()
        .split("|")
    )

    def normalize(value: str) -> str | None:
        value = value.strip()

        if (
            not value
            or value.upper()
            in {
                "NA",
                "N/A",
                "UNKNOWN",
            }
        ):
            return None

        return value

    return {
        "percent": (
            normalize(parts[0])
            if len(parts) > 0
            else None
        ),
        "speed": (
            normalize(parts[1])
            if len(parts) > 1
            else None
        ),
        "eta": (
            normalize(parts[2])
            if len(parts) > 2
            else None
        ),
    }


def extract_written_subtitle_path(
    line: str,
    output_dir: Path,
) -> Path | None:
    marker = "Writing video subtitles to:"

    if marker not in line:
        return None

    raw_path = (
        line
        .split(marker, 1)[1]
        .strip()
        .strip('"')
    )

    if not raw_path:
        return None

    path = Path(raw_path)

    if not path.is_absolute():
        candidate = (
            output_dir
            / path
        )

        if (
            candidate.exists()
            or not path.parent.parts
        ):
            path = candidate

    return path


def execute(
    job_id: str,
    cmd: list[str],
    message: str,
    output_dir: Path,
) -> tuple[int, list[str], list[Path]]:
    tail = deque(maxlen=24)
    subtitle_sources: list[Path] = []

    print(
        "[JOB]",
        job_id,
        " ".join(
            redact_line(arg)
            for arg in cmd
        ),
    )

    creationflags = 0

    if os.name == "nt":
        creationflags = getattr(
            subprocess,
            "CREATE_NO_WINDOW",
            0,
        )

    proc = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        bufsize=1,
        creationflags=creationflags,
        env=child_env(),
    )

    assert proc.stdout is not None

    for raw_line in proc.stdout:
        line = raw_line.rstrip()

        if line.startswith("VH_SUBTITLE:"):
            try:
                for value in (json.loads(line[len("VH_SUBTITLE:"):]) or {}).values():
                    if value.get("filepath"):
                        subtitle_sources.append(Path(value["filepath"]))
            except (ValueError, AttributeError, TypeError):
                pass
            continue

        subtitle_path = extract_written_subtitle_path(
            line,
            output_dir,
        )

        if (
            subtitle_path is not None
            and subtitle_path not in subtitle_sources
        ):
            subtitle_sources.append(
                subtitle_path
            )

        safe_line = redact_line(line)

        if safe_line:
            print(
                f"[yt-dlp:{job_id}] "
                f"{safe_line}"
            )

            tail.append(
                safe_line
            )

        progress = parse_progress(line)

        if progress:
            update_job(
                job_id,
                state="downloading",
                message=message,
                **progress,
            )

        elif (
            "merging formats"
            in line.lower()
        ):
            update_job(
                job_id,
                state="processing",
                message="正在合并视频和音频",
                percent="100%",
            )

        elif (
            "[extractaudio]"
            in line.lower()
        ):
            update_job(
                job_id,
                state="processing",
                message="正在提取音频",
                percent="100%",
            )

    proc.stdout.close()
    return (
        proc.wait(),
        list(tail),
        subtitle_sources,
    )


def tail_message(
    lines: list[str],
    limit: int = 900,
) -> str:
    value = " | ".join(lines)
    if "Unable to connect to proxy" in value or "ProxyError" in value:
        return network_error_message(value)

    if len(value) > limit:
        return value[-limit:]

    return value


def has_http_429(
    lines: list[str],
) -> bool:
    value = "\n".join(lines).lower()

    return (
        "http error 429"
        in value
        or "too many requests"
        in value
    )


