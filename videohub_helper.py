class Handler(BaseHTTPRequestHandler):
    server_version = (
        f"VideoHub/{VERSION}"
    )

    def log_message(
        self,
        fmt,
        *args,
    ):
        print(
            f"[HTTP] "
            f"{self.address_string()} - "
            f"{fmt % args}"
        )

    def _valid_host(self) -> bool:
        return (
            self.headers.get(
                "Host",
                "",
            )
            in {
                f"127.0.0.1:{PORT}",
                f"localhost:{PORT}",
                "127.0.0.1",
                "localhost",
            }
        )

    def _authorized(self) -> bool:
        return secrets.compare_digest(
            self.headers.get(
                "X-Local-Token",
                "",
            ),
            server_token,
        )

    def _json(
        self,
        status: int,
        payload: dict,
    ):
        raw = json.dumps(
            payload,
            ensure_ascii=False,
        ).encode("utf-8")

        self.send_response(status)
        self.send_header(
            "Content-Type",
            "application/json; charset=utf-8",
        )
        self.send_header(
            "Content-Length",
            str(len(raw)),
        )
        self.send_header(
            "Cache-Control",
            "no-store",
        )
        self.end_headers()
        self.wfile.write(raw)

    def do_GET(self):
        if not self._valid_host():
            return self._json(
                403,
                {
                    "error":
                    "Invalid Host header"
                },
            )

        u = urlparse(self.path)

        if u.path == "/health":
            return self._json(
                200,
                {
                    "ok": True,
                    "version": VERSION,
                    "subtitle_selection_types": True,
                    "subtitle_fallback": True,
                    "token": server_token,
                    "yt_dlp_version":
                    package_version("yt-dlp"),
                    "ffmpeg":
                    ffmpeg_available(),
                    "curl_cffi":
                    bool(
                        package_version(
                            "curl_cffi"
                        )
                    ),
                    "download_dir":
                    str(DOWNLOAD_ROOT),
                    "video_profile":
                    CONFIG.get(
                        "video_profile",
                        "windows_compatible",
                    ),
                    "clean_rolling_subtitles":
                    bool(
                        CONFIG.get(
                            "clean_rolling_subtitles",
                            True,
                        )
                    ),
                },
            )

        if u.path == "/status":
            if not self._authorized():
                return self._json(
                    403,
                    {
                        "error":
                        "Unauthorized"
                    },
                )

            job_id = (
                parse_qs(u.query)
                .get("id", [""])[0]
            )

            with jobs_lock:
                job = jobs.get(job_id)

            if job:
                return self._json(
                    200,
                    dict(job),
                )

            return self._json(
                404,
                {
                    "error":
                    "任务不存在"
                },
            )

        return self._json(
            404,
            {
                "error":
                "Not Found"
            },
        )

    def do_POST(self):
        if not self._valid_host():
            return self._json(
                403,
                {
                    "error":
                    "Invalid Host header"
                },
            )

        if not self._authorized():
            return self._json(
                403,
                {
                    "error":
                    "Unauthorized"
                },
            )

        if (
            urlparse(self.path).path
            not in {"/download", "/subtitles", "/playlist", "/batch"}
        ):
            return self._json(
                404,
                {
                    "error":
                    "Not Found"
                },
            )

        try:
            length = int(
                self.headers.get(
                    "Content-Length",
                    "0",
                )
            )

            if (
                length <= 0
                or length > 65_536
            ):
                raise ValueError(
                    "请求体大小无效"
                )

            payload = json.loads(
                self.rfile
                .read(length)
                .decode("utf-8")
            )

            if not isinstance(payload, dict):
                raise ValueError("请求体必须是 JSON 对象")

            route = urlparse(self.path).path
            if route == "/playlist":
                return self._json(200, list_playlist(str(payload.get("url", "")),
                                                     bool(payload.get("use_cookies", False))))
            batch_urls = validate_batch_urls(payload.get("urls")) if route == "/batch" else None
            if batch_urls:
                payload["url"] = batch_urls[0]

            platform, url = validate_single_item_url(
                str(
                    payload.get(
                        "url",
                        "",
                    )
                ).strip()
            )

            url = clean_url_for_platform(
                platform,
                url,
            )

            if urlparse(self.path).path == "/subtitles":
                tracks = list_subtitle_tracks(platform, url, bool(payload.get("use_cookies", False)))
                return self._json(200, {"tracks": tracks})

            subtitle_tracks = validate_subtitle_tracks(payload.get("subtitle_tracks"))

            mode = str(
                payload.get(
                    "mode",
                    "",
                )
            ).strip()

            if mode not in {
                "video",
                "audio",
                "subtitle",
            }:
                raise ValueError(
                    "mode 必须是 "
                    "video / audio / subtitle"
                )

            use_cookies = bool(
                payload.get(
                    "use_cookies",
                    False,
                )
            )

            include_subtitles = bool(
                payload.get(
                    "include_subtitles",
                    True,
                )
            )

            job_id = (
                uuid.uuid4().hex[:12]
            )

            with jobs_lock:
                jobs[job_id] = {
                    "job_id": job_id,
                    "platform": platform,
                    "platform_name":
                    PLATFORM_NAMES[platform],
                    "state": "queued",
                    "mode": mode,
                    "percent": None,
                    "speed": None,
                    "eta": None,
                    "message": "任务已创建",
                    "warning": None,
                }

            threading.Thread(
                target=run_batch if batch_urls else run_download,
                args=(job_id, batch_urls, mode, use_cookies, include_subtitles, subtitle_tracks)
                if batch_urls else (
                    job_id,
                    platform,
                    url,
                    mode,
                    use_cookies,
                    include_subtitles,
                    subtitle_tracks,
                ),
                daemon=True,
            ).start()

            return self._json(
                202,
                {
                    "ok": True,
                    "job_id": job_id,
                    "platform": platform,
                    "platform_name":
                    PLATFORM_NAMES[platform],
                },
            )

        except (
            ValueError,
            json.JSONDecodeError,
        ) as exc:
            return self._json(
                400,
                {
                    "error":
                    str(exc)
                },
            )

        except Exception as exc:
            traceback.print_exc()

            return self._json(
                500,
                {
                    "error":
                    redact_line(
                        str(exc)
                    )[:900]
                },
            )


