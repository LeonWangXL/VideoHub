def update_job(job_id: str, **fields) -> None:
    with jobs_lock:
        if job_id in jobs:
            job = jobs[job_id]
            job.update(fields)
            parent = jobs.get(job.get("parent_id"))
            if parent is not None:
                parent.update(state="downloading", speed=job.get("speed"), eta=job.get("eta"),
                              message=f"第 {job['batch_index']}/{job['batch_total']} 项：{job.get('message', '处理中')}",
                              percent=job.get("percent"))


def redact_line(line: str) -> str:
    def repl(match):
        try:
            u = urlparse(match.group(0))
            return urlunparse(
                (u.scheme, u.netloc, u.path, "", "", "")
            )
        except Exception:
            return "<url>"

    line = re.sub(
        r"https?://[^\s<>'\"]+",
        repl,
        line,
    )
    line = re.sub(
        r"(?i)(cookie|authorization|token)=\S+",
        r"\1=<redacted>",
        line,
    )
    return line.strip()


# ---------------------------------------------------------------------------
# SRT rolling-caption cleaner
# ---------------------------------------------------------------------------

SRT_TIMING_RE = re.compile(
    r"^\s*"
    r"(\d{2}:\d{2}:\d{2},\d{3})"
    r"\s*-->\s*"
    r"(\d{2}:\d{2}:\d{2},\d{3})"
    r"(?:\s+.*)?$"
)

HTML_TAG_RE = re.compile(r"<[^>]+>")


def srt_time_to_ms(value: str) -> int:
    hh, mm, tail = value.split(":")
    ss, msec = tail.split(",")

    return (
        ((int(hh) * 60 + int(mm)) * 60 + int(ss)) * 1000
        + int(msec)
    )


def ms_to_srt_time(value: int) -> str:
    value = max(0, int(value))

    hh, rem = divmod(value, 3_600_000)
    mm, rem = divmod(rem, 60_000)
    ss, msec = divmod(rem, 1_000)

    return f"{hh:02d}:{mm:02d}:{ss:02d},{msec:03d}"


def parse_srt(text: str) -> list[dict]:
    """
    Line-oriented parser.

    It intentionally tolerates an empty line between the timing line and
    subtitle text, since copied/converted SRT files are not always perfectly
    canonical.
    """
    lines = (
        text
        .replace("\r\n", "\n")
        .replace("\r", "\n")
        .split("\n")
    )

    cues: list[dict] = []
    i = 0

    while i < len(lines):
        line = lines[i].strip()

        # Optional numeric cue index.
        if (
            line.isdigit()
            and i + 1 < len(lines)
            and SRT_TIMING_RE.match(lines[i + 1].strip())
        ):
            i += 1
            line = lines[i].strip()

        match = SRT_TIMING_RE.match(line)
        if not match:
            i += 1
            continue

        start_ms = srt_time_to_ms(match.group(1))
        end_ms = srt_time_to_ms(match.group(2))

        i += 1
        text_lines: list[str] = []

        while i < len(lines):
            current = lines[i]
            stripped = current.strip()

            # A timing line means the next cue has begun.
            if SRT_TIMING_RE.match(stripped):
                break

            # Numeric index immediately followed by timing means next cue.
            if (
                stripped.isdigit()
                and i + 1 < len(lines)
                and SRT_TIMING_RE.match(lines[i + 1].strip())
            ):
                break

            if stripped:
                text_lines.append(stripped)

            i += 1

        if text_lines and end_ms > start_ms:
            cues.append(
                {
                    "start": start_ms,
                    "end": end_ms,
                    "lines": text_lines,
                }
            )

    return cues


def normalize_subtitle_line(value: str) -> str:
    value = HTML_TAG_RE.sub("", value)
    value = (
        value
        .replace("\u200b", "")
        .replace("\ufeff", "")
    )

    return re.sub(r"\s+", " ", value).strip()


def normalized_lines(cue: dict) -> list[str]:
    result = []

    for line in cue["lines"]:
        normalized = normalize_subtitle_line(line)
        if normalized:
            result.append(normalized)

    return result


def cue_tokens(cue: dict) -> list[str]:
    result: list[str] = []

    for line in normalized_lines(cue):
        result.extend(line.split())

    return result


def classify_caption_transition(
    previous: dict,
    current: dict,
    min_overlap_tokens: int,
) -> tuple[str, list[str]]:
    """
    Classify how current relates to previous.

    Returns:
      ("same", [])
      ("carry", [])
      ("rolling_new", [new text lines...])
      ("independent", [full current text...])

    Example:
      previous = ["hello there"]
      current  = ["hello there", "how are you"]
      => rolling_new / ["how are you"]

      previous = ["hello there", "how are you"]
      current  = ["how are you"]
      => carry / []
    """
    prev_lines = normalized_lines(previous)
    curr_lines = normalized_lines(current)

    if not prev_lines or not curr_lines:
        return "independent", list(current["lines"])

    if prev_lines == curr_lines:
        return "same", []

    # Strongest and safest signal: complete line overlap.
    max_line_overlap = min(
        len(prev_lines),
        len(curr_lines),
    )

    for overlap in range(max_line_overlap, 0, -1):
        if prev_lines[-overlap:] == curr_lines[:overlap]:
            if overlap == len(curr_lines):
                return "carry", []

            # Preserve the original current text, including punctuation/tags.
            return (
                "rolling_new",
                list(current["lines"][overlap:]),
            )

    # Fallback for YouTube changing line wrapping while keeping the words.
    prev_tokens = cue_tokens(previous)
    curr_tokens = cue_tokens(current)

    max_token_overlap = min(
        len(prev_tokens),
        len(curr_tokens),
    )

    for overlap in range(max_token_overlap, 0, -1):
        if prev_tokens[-overlap:] != curr_tokens[:overlap]:
            continue

        overlap_chars = sum(
            len(token)
            for token in curr_tokens[:overlap]
        )

        # Require substantial token overlap to avoid deleting ordinary speech
        # that happens to repeat one or two words.
        if (
            overlap < min_overlap_tokens
            and overlap_chars < 24
        ):
            continue

        if overlap == len(curr_tokens):
            return "carry", []

        return (
            "rolling_new",
            [" ".join(curr_tokens[overlap:])],
        )

    return "independent", list(current["lines"])


def detect_rolling_captions(
    cues: list[dict],
    min_overlap_tokens: int,
) -> tuple[bool, dict]:
    rolling_new = 0
    carry = 0
    tiny_carry = 0

    for i in range(1, len(cues)):
        relation, _ = classify_caption_transition(
            cues[i - 1],
            cues[i],
            min_overlap_tokens,
        )

        if relation == "rolling_new":
            rolling_new += 1

        elif relation in {"same", "carry"}:
            carry += 1

            duration = (
                cues[i]["end"]
                - cues[i]["start"]
            )
            if duration <= 80:
                tiny_carry += 1

    # Conservative detection:
    # one accidental repeated sentence should not rewrite an ordinary SRT.
    detected = (
        rolling_new >= 2
        or (
            rolling_new >= 1
            and carry >= 2
        )
        or (
            rolling_new >= 1
            and tiny_carry >= 1
        )
    )

    return (
        detected,
        {
            "rolling_new": rolling_new,
            "carry": carry,
            "tiny_carry": tiny_carry,
        },
    )


def deroll_srt_cues(
    cues: list[dict],
    min_overlap_tokens: int,
) -> tuple[list[dict], bool, dict]:
    if len(cues) < 2:
        return cues, False, {}

    detected, detection_stats = detect_rolling_captions(
        cues,
        min_overlap_tokens,
    )

    if not detected:
        return cues, False, detection_stats

    output: list[dict] = [
        {
            "start": cues[0]["start"],
            "end": cues[0]["end"],
            "lines": list(cues[0]["lines"]),
        }
    ]

    active_index = 0
    previous_raw = cues[0]

    for current in cues[1:]:
        relation, novel_lines = classify_caption_transition(
            previous_raw,
            current,
            min_overlap_tokens,
        )

        if relation in {"same", "carry"}:
            # The current cue is just the currently visible text carried
            # forward. Extend the clean cue instead of emitting a duplicate.
            output[active_index]["end"] = max(
                output[active_index]["end"],
                current["end"],
            )

        elif relation == "rolling_new":
            # New words appear exactly at current.start. The previously
            # emitted phrase should stop there; the new phrase starts there.
            output[active_index]["end"] = max(
                output[active_index]["start"] + 1,
                current["start"],
            )

            novel_lines = [
                line.strip()
                for line in novel_lines
                if line.strip()
            ]

            if novel_lines:
                output.append(
                    {
                        "start": current["start"],
                        "end": current["end"],
                        "lines": novel_lines,
                    }
                )
                active_index = len(output) - 1

        else:
            # Normal non-rolling subtitle transition.
            output.append(
                {
                    "start": current["start"],
                    "end": current["end"],
                    "lines": list(current["lines"]),
                }
            )
            active_index = len(output) - 1

        previous_raw = current

    # Final sanity pass: remove adjacent exact duplicates and invalid durations.
    cleaned: list[dict] = []

    for cue in output:
        cue = {
            "start": int(cue["start"]),
            "end": int(cue["end"]),
            "lines": list(cue["lines"]),
        }

        if cue["end"] <= cue["start"]:
            cue["end"] = cue["start"] + 1

        if (
            cleaned
            and normalized_lines(cleaned[-1])
            == normalized_lines(cue)
            and cue["start"]
            <= cleaned[-1]["end"] + 50
        ):
            cleaned[-1]["end"] = max(
                cleaned[-1]["end"],
                cue["end"],
            )
        else:
            cleaned.append(cue)

    return cleaned, True, detection_stats


def render_srt(cues: list[dict]) -> str:
    blocks = []

    for index, cue in enumerate(cues, 1):
        block = [
            str(index),
            (
                f"{ms_to_srt_time(cue['start'])}"
                f" --> "
                f"{ms_to_srt_time(cue['end'])}"
            ),
            *cue["lines"],
        ]

        blocks.append("\n".join(block))

    return "\n\n".join(blocks) + "\n"


def clean_srt_file(path: Path) -> dict:
    """
    Clean a single SRT atomically.

    Returns a result dict suitable for logs/status text.
    """
    path = Path(path)

    if not path.exists():
        return {
            "changed": False,
            "reason": "not_found",
            "path": str(path),
        }

    raw = path.read_text(
        encoding="utf-8-sig",
        errors="replace",
    )

    cues = parse_srt(raw)

    if len(cues) < 2:
        return {
            "changed": False,
            "reason": "too_few_cues",
            "path": str(path),
            "before": len(cues),
            "after": len(cues),
        }

    min_overlap_tokens = max(
        2,
        int(
            CONFIG.get(
                "subtitle_cleanup_min_overlap_tokens",
                4,
            )
            or 4
        ),
    )

    cleaned, detected, detection_stats = deroll_srt_cues(
        cues,
        min_overlap_tokens,
    )

    if not detected:
        return {
            "changed": False,
            "reason": "not_rolling",
            "path": str(path),
            "before": len(cues),
            "after": len(cues),
            "detection": detection_stats,
        }

    # Defensive guard against a parser/heuristic failure.
    if not cleaned or len(cleaned) > len(cues):
        return {
            "changed": False,
            "reason": "sanity_guard",
            "path": str(path),
            "before": len(cues),
            "after": len(cleaned),
            "detection": detection_stats,
        }

    if bool(
        CONFIG.get(
            "subtitle_cleanup_keep_backup",
            False,
        )
    ):
        backup = path.with_name(
            path.stem
            + ".raw"
            + path.suffix
        )

        if not backup.exists():
            shutil.copy2(path, backup)

    temp_path = path.with_name(
        path.name
        + ".videohub.tmp"
    )

    temp_path.write_text(
        render_srt(cleaned),
        encoding="utf-8",
        newline="\n",
    )

    os.replace(
        temp_path,
        path,
    )

    return {
        "changed": True,
        "reason": "rolling_cleaned",
        "path": str(path),
        "before": len(cues),
        "after": len(cleaned),
        "removed": len(cues) - len(cleaned),
        "detection": detection_stats,
    }


def clean_generated_srt_files(
    platform: str,
    subtitle_source_paths: list[Path],
) -> list[dict]:
    """
    yt-dlp prints the pre-conversion subtitle path, e.g. .en.vtt.
    --convert-subs srt creates the same basename with .srt.
    """
    if platform != "youtube":
        return []

    if not bool(
        CONFIG.get(
            "clean_rolling_subtitles",
            True,
        )
    ):
        return []

    results = []
    seen = set()

    for source_path in subtitle_source_paths:
        source_path = Path(source_path)

        candidates = []

        if source_path.suffix.lower() == ".srt":
            candidates.append(source_path)
        else:
            candidates.append(
                source_path.with_suffix(".srt")
            )

        for srt_path in candidates:
            key = str(srt_path).lower()

            if key in seen:
                continue

            seen.add(key)

            try:
                result = clean_srt_file(srt_path)
                results.append(result)

                if result.get("changed"):
                    print(
                        "[SUB CLEAN]",
                        srt_path.name,
                        f"{result['before']} -> {result['after']} cues",
                    )

            except Exception as exc:
                print(
                    f"[WARN] 字幕去重失败 {srt_path}: {exc}"
                )

    return results


def cleanup_summary(results: list[dict]) -> str:
    changed = [
        item
        for item in results
        if item.get("changed")
    ]

    if not changed:
        return ""

    before = sum(
        int(item.get("before") or 0)
        for item in changed
    )
    after = sum(
        int(item.get("after") or 0)
        for item in changed
    )

    return (
        f"；字幕滚动去重 {before}→{after} 条"
    )


