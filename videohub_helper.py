def proxy_arguments():
    proxy = CONFIG.get("proxy")
    if proxy is None:
        return []
    if not isinstance(proxy, str):
        raise ValueError("config.json 中 proxy 必须为 URL 字符串、空字符串或 null")
    if proxy:
        u = urlparse(proxy)
        try:
            valid = u.scheme in {"http", "https", "socks4", "socks4a", "socks5", "socks5h"} and u.hostname and u.port
        except ValueError:
            valid = False
        if not valid:
            raise ValueError("config.json 中 proxy 地址无效，例如 http://127.0.0.1:17891")
    return ["--proxy", proxy]


def network_error_message(value):
    if "Unable to connect to proxy" in value or "ProxyError" in value:
        return ("无法连接代理服务器。请确认代理程序正在运行，且 config.json 中 proxy 端口正确；"
                "未配置 proxy 时会继承环境变量或系统代理。修改配置后请重启 VideoHub 本地服务。")
    return redact_line(value)[-900:]


def common_command(
    platform: str,
    use_cookies: bool,
) -> list[str]:
    if not package_version("yt-dlp"):
        raise RuntimeError(
            "未安装 yt-dlp，请运行: "
            'python -m pip install -U '
            '"yt-dlp[default,curl-cffi]"'
        )

    cmd = [
        sys.executable,
        "-m",
        "yt_dlp",
        "--newline",
        "--no-colors",
        "--no-playlist",
        "--retries",
        "5",
        "--fragment-retries",
        "5",
        "--extractor-retries",
        "3",
        "--progress",
        "--progress-template",
        (
            "download:VH_PROGRESS:"
            "%(progress._percent_str)s|"
            "%(progress._speed_str)s|"
            "%(progress._eta_str)s"
        ),
        "-P",
        str(platform_dir(platform)),
        "-o",
        "%(title).180B [%(id)s].%(ext)s",
    ]

    cmd += proxy_arguments()

    if use_cookies:
        cmd += [
            "--cookies-from-browser",
            browser_cookie_spec(),
        ]

    return cmd


def media_command(
    platform: str,
    url: str,
    mode: str,
    use_cookies: bool,
) -> list[str]:
    cmd = common_command(
        platform,
        use_cookies,
    )

    if mode == "video":
        profile = str(
            CONFIG.get(
                "video_profile",
                "windows_compatible",
            )
            or "windows_compatible"
        ).strip()

        if profile == "windows_compatible":
            if platform == "youtube":
                # Strict Windows-friendly profile:
                # H.264/AVC + AAC/M4A in MP4.
                selector = (
                    "bv[ext=mp4][vcodec^=avc]"
                    "+"
                    "ba[ext=m4a][acodec^=mp4a]"
                    "/"
                    "b[ext=mp4]"
                    "[vcodec^=avc]"
                    "[acodec^=mp4a]"
                )

                cmd += [
                    "-f",
                    selector,
                ]

                if ffmpeg_available():
                    cmd += [
                        "--merge-output-format",
                        "mp4",
                    ]

            else:
                # yt-dlp's mp4 preset prefers H.264 + AAC while remaining
                # tolerant of non-YouTube extractor format layouts.
                cmd += [
                    "-t",
                    "mp4",
                ]

        elif profile == "best_quality":
            cmd += [
                "-f",
                "bv*+ba/b",
            ]

            if ffmpeg_available():
                cmd += [
                    "--merge-output-format",
                    "mp4",
                ]

        else:
            raise ValueError(
                "video_profile 必须是 "
                "windows_compatible 或 best_quality"
            )

    elif mode == "audio":
        if not ffmpeg_available():
            raise RuntimeError(
                "提取 MP3 需要 FFmpeg/ffprobe"
            )

        cmd += [
            "-x",
            "--audio-format",
            "mp3",
            "--audio-quality",
            "0",
        ]

    else:
        raise ValueError(
            "mode 必须是 video / audio"
        )

    cmd.append(url)
    return cmd


def validate_subtitle_tracks(value):
    if value is None:
        return None
    if not isinstance(value, list) or len(value) > 30:
        raise ValueError("字幕选择必须是列表，最多 30 项")
    result = []
    for item in value:
        if (not isinstance(item, dict) or item.get("source") not in {"manual", "auto"}
                or not isinstance(item.get("language"), str)
                or not re.fullmatch(r"[A-Za-z0-9_.-]{1,100}", item["language"])
                or item["language"] == "live_chat"):
            raise ValueError("字幕选项无效，请重新加载字幕列表")
        track = {"source": item["source"], "language": item["language"]}
        if "translated" in item:
            if not isinstance(item["translated"], bool) or (item["source"] == "manual" and item["translated"]):
                raise ValueError("字幕翻译类型无效")
            track["translated"] = item["translated"]
        if "fallback" in item:
            if not isinstance(item["fallback"], str) or item["fallback"] not in {"none", "zh-auto"}:
                raise ValueError("字幕缺失处理选项无效")
            track["fallback"] = item["fallback"]
        if track not in result:
            result.append(track)
    return result


def list_subtitle_tracks(platform, url, use_cookies):
    print(f"[SUBTITLES] 开始查询 {clean_url_for_platform(platform, url)}", flush=True)
    cmd = common_command(platform, use_cookies)
    cmd += ["--ignore-config", "--skip-download", "--ignore-no-formats-error", "--dump-single-json", url]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                              errors="replace", env=child_env(), timeout=90)
    except subprocess.TimeoutExpired:
        print("[SUBTITLES] 查询超时（90 秒），请重试", flush=True)
        raise ValueError("字幕列表解析超时，请稍后重试") from None
    if proc.returncode:
        print("[SUBTITLES] 查询失败：" + network_error_message(proc.stderr), flush=True)
        raise ValueError(network_error_message(proc.stderr) or "字幕列表解析失败")
    info = json.loads(proc.stdout)
    tracks = []
    for source, key in (("manual", "subtitles"), ("auto", "automatic_captions")):
        for language, formats in (info.get(key) or {}).items():
            if language == "live_chat" or not formats:
                continue
            if not re.fullmatch(r"[A-Za-z0-9_.-]{1,100}", language):
                continue
            translated = source == "auto" and any(
                "tlang" in parse_qs(urlparse(f.get("url", "")).query) for f in formats)
            tracks.append({"language": language, "source": source,
                           "name": formats[0].get("name") or language,
                           "translated": translated})
    print(f"[SUBTITLES] 查询完成：{len(tracks)} 种字幕", flush=True)
    return sorted(tracks, key=lambda t: (t["translated"], t["source"] == "auto", t["language"]))


def subtitle_command(
    platform: str,
    url: str,
    use_cookies: bool,
    sleep_seconds: int = 0,
    track: dict | None = None,
) -> list[str]:
    cmd = common_command(
        platform,
        use_cookies,
    )

    langs = (
        CONFIG.get("subtitle_languages")
        or ["en"]
    )

    if not isinstance(langs, list):
        langs = ["en"]

    langs = [
        str(item).strip()
        for item in langs
        if str(item).strip()
    ] or ["en"]

    cmd += [
        "--skip-download",
        "--write-subs",
        "--sub-langs",
        re.escape(track["language"]) if track else ",".join(langs),
    ]

    if bool(
        CONFIG.get(
            "write_auto_subtitles",
            True,
        )
    ):
        cmd.append(
            "--write-auto-subs"
        )

    if sleep_seconds > 0:
        cmd += [
            "--sleep-subtitles",
            str(sleep_seconds),
        ]

    if ffmpeg_available():
        cmd += [
            "--convert-subs",
            "srt",
        ]

    cmd += ["--ignore-config", "--ignore-no-formats-error", "--sub-format", "vtt/best",
            "--no-simulate", "--no-quiet", "--print", "after_video:VH_SUBTITLE:%(requested_subtitles)j"]
    if track:
        # Exact language matching; manual and auto tracks are downloaded separately.
        cmd += (["--no-write-subs", "--write-auto-subs"] if track["source"] == "auto"
                else ["--write-subs", "--no-write-auto-subs"])
        cmd += ["-o", "%(title).180B [%(id)s]." + track["source"] + ".%(ext)s"]
    cmd.append(url)
    return cmd


