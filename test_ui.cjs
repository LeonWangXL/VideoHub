const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('https://www.youtube.com/**', route => route.fulfill({ contentType: 'text/html', body: '<html><head><style>body{background:#e8ecf2;font:20px sans-serif;color:#aab0bc;padding:40px} button,label{color:black!important;opacity:.1!important} </style></head><body><h1>VideoHub UI verification</h1><p>Host-page styles must not affect the download panel.</p></body></html>' }));
  await page.goto('https://www.youtube.com/watch?v=9LKJ8JdLtfI&list=fixture');
  await page.evaluate(() => {
    window.GM_getValue = (_, fallback) => fallback;
    window.GM_setValue = () => {};
    window.GM_notification = () => {};
    window.submissions = [];
    window.pollCount = 0;
    window.GM_xmlhttpRequest = options => {
      const route = new URL(options.url).pathname;
      let data;
      if (route === '/health') data = { token: 'fixture', ffmpeg: true, yt_dlp_version: 'test', subtitle_selection_types: true, subtitle_fallback: true };
      if (route === '/playlist') data = { title: '学习课程 · 示例播放列表', items: Array.from({ length: 48 }, (_, i) => ({ index: i + 1, title: i === 0 ? '第一课：如何理解长期积累和复利的价值' : `第 ${i + 1} 课：学习方法、思维训练与实践案例`, url: `https://www.youtube.com/watch?v=fixture${String(i).padStart(4, '0')}` })) };
      if (route === '/subtitles') data = { tracks: [{ language: 'zh', name: '中文', source: 'manual' }, { language: 'en-orig', name: 'English', source: 'auto' }] };
      if (route === '/batch' || route === '/download') { window.submissions.push({ route, body: JSON.parse(options.data) }); data = { job_id: 'fixture-job' }; window.pollCount = 0; }
      if (route === '/status') {
        window.pollCount++;
        data = window.pollCount === 1 ? { state: 'downloading', message: '第 2/48 项：正在下载中文字幕', total: 48, completed: 1, percent: '26%' }
          : { state: 'error', message: '成功 47，失败 1', total: 48, completed: 48, results: [{ url: 'https://www.youtube.com/watch?v=fixture0000', state: 'error', message: '此视频未提供所选字幕' }] };
      }
      setTimeout(() => options.onload({ status: 200, responseText: JSON.stringify(data) }), 10);
    };
  });
  await page.addScriptTag({ path: path.resolve('videohub.user.js') });
  const root = page.locator('#videohub-userscript-v200');
  const launcher = root.getByRole('button', { name: /↓ VideoHub/ });
  await launcher.click();
  await root.getByRole('button', { name: '当前视频', exact: true }).waitFor();
  assert.equal(await root.getByRole('dialog').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(25, 28, 34)');
  assert.equal(await root.getByRole('button', { name: '当前视频', exact: true }).evaluate(el => getComputedStyle(el).opacity), '1');
  fs.mkdirSync('.verification/ui', { recursive: true });
  assert.equal(await root.getByRole('button', { name: '加载 / 刷新播放列表', exact: true }).isVisible(), false);
  await page.screenshot({ path: '.verification/ui/current-video.png' });
  await root.getByRole('button', { name: '播放列表', exact: true }).click();
  assert.equal(await root.getByRole('button', { name: /下载所选 0 项/ }).isDisabled(), true);
  await root.getByRole('button', { name: '加载 / 刷新播放列表', exact: true }).click();
  await root.getByText('已选 48 / 48 项', { exact: true }).waitFor();
  await root.getByRole('searchbox').fill('第一课');
  assert.equal(await root.locator('.vh-playlist label:visible').count(), 1);
  await root.locator('.vh-playlist label:visible input').uncheck();
  assert.equal(await root.getByLabel('全选全部').evaluate(el => el.indeterminate), true);
  await root.getByText('已选 47 / 48 项', { exact: true }).waitFor();
  await root.getByRole('searchbox').fill('');
  await root.getByLabel('全选全部').check();
  await root.getByLabel('下载内容', { exact: true }).selectOption('subtitle');
  assert.equal(await root.getByLabel('所选语言或来源缺失时').inputValue(), 'zh-auto');
  await root.getByLabel('字幕选择方式').selectOption('custom');
  await root.getByLabel('自动生成 · 语音识别原文', { exact: true }).uncheck();
  assert.equal(await root.getByRole('button', { name: /下载所选 48 项字幕/ }).isDisabled(), true);
  await root.getByLabel('原始字幕 · 作者上传', { exact: true }).check();
  await root.getByLabel('英文', { exact: true }).check();
  await root.getByLabel('自动生成 · 语音识别原文', { exact: true }).check();
  await root.getByLabel('英文', { exact: true }).uncheck();
  await root.getByLabel('自动生成 · 语音识别原文', { exact: true }).uncheck();
  await root.getByRole('button', { name: '查看当前视频可用字幕', exact: true }).click();
  await root.getByText(/已查询当前视频的字幕/).waitFor();
  await root.locator('.vh-body').evaluate(el => { el.scrollTop = 140; });
  await root.getByRole('dialog').screenshot({ path: '.verification/ui/subtitle-settings.png' });
  await root.getByText('字幕设置 · 中文 / 原始字幕', { exact: true }).click();
  await root.locator('.vh-body').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: '.verification/ui/playlist-desktop.png' });
  await root.getByRole('dialog').screenshot({ path: '.verification/ui/panel-preview.png' });
  await page.setViewportSize({ width: 390, height: 740 });
  await root.locator('.vh-body').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: '.verification/ui/playlist-mobile.png' });
  const panel = await root.getByRole('dialog').boundingBox();
  assert(panel.x >= 0 && panel.y >= 0 && panel.x + panel.width <= 390 && panel.y + panel.height <= 740);
  const footer = await root.locator('.vh-footer').boundingBox();
  assert(footer.y + footer.height <= 740);
  await root.getByRole('button', { name: /下载所选 48 项字幕/ }).click();
  await root.getByText('第 2/48 项：正在下载中文字幕', { exact: false }).waitFor();
  await page.screenshot({ path: '.verification/ui/downloading-mobile.png' });
  assert.equal(await root.getByRole('button', { name: '播放列表', exact: true }).isDisabled(), true);
  await root.getByText('失败：成功 47，失败 1', { exact: false }).waitFor();
  await root.getByText('逐项结果 / 失败重试', { exact: true }).click();
  await root.getByRole('button', { name: '重试失败或字幕不完整的条目', exact: true }).click();
  await page.waitForFunction(() => window.submissions.length === 2);
  const requests = await page.evaluate(() => window.submissions);
  assert.equal(requests[0].route, '/batch');
  assert.equal(requests[0].body.urls.length, 48);
  assert.deepEqual(requests[0].body.subtitle_tracks, [{ language: 'zh-Hans', source: 'manual', translated: false, fallback: 'zh-auto' }]);
  assert.equal(requests[1].body.urls.length, 1);
  await root.getByRole('button', { name: '关闭下载面板', exact: true }).click();
  assert.equal(await root.getByRole('dialog').isVisible(), false);
  await launcher.click();
  await root.getByText('失败：成功 47，失败 1', { exact: false }).waitFor();
  await root.getByRole('button', { name: '当前视频', exact: true }).click();
  await root.getByLabel('下载内容', { exact: true }).selectOption('audio');
  await root.getByRole('button', { name: '下载当前音频', exact: true }).click();
  await page.waitForFunction(() => window.submissions.length === 3);
  const single = await page.evaluate(() => window.submissions[2]);
  assert.equal(single.route, '/download');
  assert.equal(single.body.mode, 'audio');
  await root.getByRole('dialog').press('Escape');
  assert.equal(await root.getByRole('dialog').isVisible(), false);
  assert.deepEqual(errors, []);
  await browser.close();
  console.log('UI checks passed: style isolation, scope/mode selection, 48-item search, counts, indeterminate selection, subtitle payload, progress, retry, mobile layout, close.');
})().catch(error => { console.error(error); process.exit(1); });
